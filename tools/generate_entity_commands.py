"""Generate command discriminants from per-operation declarations, never a shared hand list.

Generated source is checked in: public types carry an explicit Wire derive in
that source, and Rust's compiler owns validation of their Rust payload types.
"""
import argparse
from dataclasses import dataclass
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
IDENT = re.compile(r'^[A-Za-z_][A-Za-z_0-9]*$')


@dataclass(frozen=True)
class Action:
    operation: str
    completion: str
    payload: str
    result: str
    error: str


def declarations(directory):
    actions = []
    seen = set()
    for path in sorted(directory.glob('*.json')):
        value = json.loads(path.read_text())
        if not isinstance(value, dict) or set(value) != {'operation', 'completion', 'payload', 'result', 'error'}:
            raise ValueError(f'{path}: expected operation/completion/payload/result/error')
        for key in ('operation', 'completion'):
            if not isinstance(value[key], str) or not IDENT.fullmatch(value[key]):
                raise ValueError(f'{path}: invalid {key} identifier')
            if (key, value[key]) in seen:
                raise ValueError(f'{path}: duplicate {key} {value[key]}')
            seen.add((key, value[key]))
        for key in ('payload', 'result', 'error'):
            if not isinstance(value[key], str) or not value[key].strip():
                raise ValueError(f'{path}: {key} must be a Rust type')
        actions.append(Action(**value))
    if not actions:
        raise ValueError(f'{directory}: no command declarations')
    return actions


def generated(actions):
    header = '// @generated by tools/generate_entity_commands.py; edit the per-operation declarations.\n'
    engine = header + 'pub(super) enum EntityOperation {\n'
    public = header + '''use crate::*;

/// Terminal operation-tagged results delivered identically by event and query.
#[derive(Clone, Debug, PartialEq, Eq, Wire)]
pub enum EntityWriteCompletion {
'''
    for action in actions:
        engine += f'    {action.operation}({action.payload}),\n'
        public += (f'    /// Actual result for the `{action.completion}` operation.\n'
                   f'    {action.completion}(CommandCompleted<{action.result}, {action.error}>),\n')
    return engine + '}\n', public + '}\n'


def outputs(root):
    actions = declarations(root / 'crates/horizon-mod-api/entity_commands')
    engine, public = generated(actions)
    return {
        root / 'crates/horizon-client/entity_operations_generated.rs': engine,
        root / 'crates/horizon-mod-api/src/entity_write_completions_generated.rs': public,
    }


def run(root=ROOT, check=False):
    stale = []
    for path, content in outputs(root).items():
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise ValueError('stale command declarations: ' + ', '.join(stale))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    run(check=args.check)
