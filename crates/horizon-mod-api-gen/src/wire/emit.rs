//! `Wire` impls for the plain data of the API: every record, tuple record, enum and variant
//! whose fields all have a wire form. `mod_api` includes the output at its root, so it reaches
//! the fields a handle keeps private to the crate, and the checked constructors a host uses
//! on what a mod sends.
use super::ty::{Case, Field, Kind, List, Payload, Str, Ty, Types};
use std::fmt::Write;

/// `ty` as Rust spells it when it is owned plain data; none for a type with no wire form.
fn spell(types: &Types<'_>, ty: &Ty) -> Option<String> {
    Some(match ty {
        Ty::Unit => "()".into(),
        Ty::Prim(rust) | Ty::Wide(rust) => (*rust).into(),
        Ty::Duration => "::std::time::Duration".into(),
        Ty::Handler(..) => super::calls::rust_ty(types, ty, false),
        Ty::Str(Str::Static) => "&'static str".into(),
        Ty::Str(Str::Owned) => "::std::string::String".into(),
        Ty::Str(Str::Cow) => "::std::borrow::Cow<'static, str>".into(),
        Ty::Str(Str::Boxed) => "::std::boxed::Box<str>".into(),
        Ty::Str(Str::Shared) => "::std::sync::Arc<str>".into(),
        Ty::List(item, List::Vec) => format!("::std::vec::Vec<{}>", spell(types, item)?),
        Ty::List(item, List::Set(set)) => format!("{set}<{}>", spell(types, item)?),
        Ty::List(item, List::Map(map)) => match &**item {
            Ty::Tuple(pair) => format!(
                "{map}<{}, {}>",
                spell(types, &pair[0])?,
                spell(types, &pair[1])?
            ),
            _ => return None,
        },
        Ty::Array(item, n) => format!("[{}; {n}]", spell(types, item)?),
        Ty::Option(item) => format!("::std::option::Option<{}>", spell(types, item)?),
        Ty::Result(ok, err) => format!(
            "::std::result::Result<{}, {}>",
            spell(types, ok)?,
            spell(types, err)?
        ),
        Ty::Tuple(items) => format!(
            "({},)",
            items
                .iter()
                .map(|i| spell(types, i))
                .collect::<Option<Vec<_>>>()?
                .join(", ")
        ),
        Ty::Boxed(inner) => format!("::std::boxed::Box<{}>", spell(types, inner)?),
        Ty::Shared(inner) => format!("::std::sync::Arc<{}>", spell(types, inner)?),
        Ty::Named(id) => {
            let def = &types.defs[*id];
            (def.lifetimes == 0).then(|| def.rust.clone())?
        }
        _ => return None,
    })
}

fn fields<'f>(types: &Types<'_>, list: &'f [Field]) -> Option<Vec<(&'f str, String)>> {
    list.iter()
        .map(|f| Some((f.rust.as_str(), spell(types, &f.ty)?)))
        .collect()
}

/// The impls for every owned def, and for each def it can't write, an assertion that one exists.
pub(super) fn types(types: &Types<'_>) -> String {
    let mut out = String::from("// @generated by horizon-mod-api-gen; do not edit.\n");
    let manual = types
        .index
        .modules
        .iter()
        .flat_map(|m| &m.items)
        .filter_map(|item| match item {
            syn::Item::Impl(i)
                if i.trait_.as_ref().is_some_and(|(_, p, _)| {
                    p.segments.last().is_some_and(|s| s.ident == "Wire")
                }) =>
            {
                Some(
                    super::ty::written(&i.self_ty)
                        .replace(' ', "")
                        .replace("crate::", "mod_api::"),
                )
            }
            _ => None,
        })
        .collect::<std::collections::HashSet<_>>();
    for owner in super::exports()
        .iter()
        .copied()
        .chain(std::iter::once(super::ERASED))
    {
        let path = super::calls::trait_path(owner);
        for (container, owned) in [("std::sync::Arc", false), ("Box", true)] {
            // Erased capabilities share an Any Arc; they cannot move an unknown
            // concrete value out of one through a boxed downcast.
            if owner == super::ERASED && owned {
                continue;
            }
            let put = if owned {
                "out.fail(crate::wire::WireError::Invalid(\"boxed handler needs owned encoding\"));"
                    .to_string()
            } else {
                "out.put_resource(Box::new(self.clone()));".into()
            };
            let transfer = if owned {
                format!(
                    "fn put_owned(self,out:&mut crate::wire::Writer) {{ out.put_resource(Box::new(std::sync::Arc::<dyn {path}>::from(self))); }}"
                )
            } else {
                String::new()
            };
            writeln!(out,"impl crate::wire::Wire for {container}<dyn {path}> {{ const MIN:usize=8; fn put(&self,out:&mut crate::wire::Writer) {{ {put} }} {transfer} fn take(input:&mut crate::wire::Reader<'_>)->Result<Self,crate::wire::WireError> {{ input.take_resource() }} }}").unwrap();
        }
    }
    for (def_id, def) in types.defs.iter().enumerate() {
        // Host-side imports must also reconstruct non-exhaustive borrowed records.
        // A typed constructor generated from public fields keeps this structural, not per-type glue.
        if def.lifetimes == 1
            && let Kind::Record(fields) = &def.kind
            && fields
                .iter()
                .all(|f| super::calls::held(types, &f.ty).is_some())
        {
            let args = fields
                .iter()
                .map(|f| {
                    format!(
                        "{}: {}",
                        f.rust,
                        borrowed(types, &f.ty)
                            .replace("'_", "'a")
                            .replace("&", "&'a ")
                            .replace("&'a 'static", "&'static")
                    )
                })
                .collect::<Vec<_>>()
                .join(",");
            let names = fields
                .iter()
                .map(|f| f.rust.as_str())
                .collect::<Vec<_>>()
                .join(",");
            writeln!(out, "#[doc(hidden)] pub fn __wire_record_{def_id}<'a>({args}) -> {}<'a> {{ {} {{ {names} }} }}", def.rust, def.rust).unwrap();
        }
        if def.append.is_some() || def.projection.is_some() {
            let put = def
                .borrow_fields()
                .unwrap()
                .iter()
                .map(|f| super::host::put(&f.ty, &format!("self.{}", f.rust)))
                .collect::<Vec<_>>()
                .join("");
            let path = &def.rust;
            writeln!(out, "impl crate::wire::Put for {path}<'_> {{ fn put_to(&self,w:&mut crate::wire::Writer) {{ {put} }} }}").unwrap();
        }
        if let Some(append) = &def.append {
            let element = super::calls::rust_ty(types, &append.element, false);
            let field = &append.fields[append.field].rust;
            let equal = super::append::equal(types, &append.element, "a", "b").unwrap();
            let path = &def.rust;
            writeln!(out, "impl {path}<'_> {{
                    #[doc(hidden)] pub fn __wire_changes(&self) -> &Vec<{element}> {{ self.{field} }}
                    #[doc(hidden)] pub fn __wire_checked(&self, mut snapshot:Vec<{element}>) -> Result<crate::wire::Append<{element}>,crate::wire::WireError> {{
                        let prefix = snapshot.get(..self.{field}.len()).ok_or(crate::wire::WireError::Invalid(\"deleted append prefix\"))?;
                        if !self.{field}.iter().zip(prefix).all(|(a,b)| {equal}) {{ return Err(crate::wire::WireError::Invalid(\"changed append prefix\")); }}
                        drop(snapshot.drain(..self.{field}.len()));
                        Ok(crate::wire::Append::new(snapshot))
                    }}
                    #[doc(hidden)] pub fn __wire_apply(&mut self, delta:crate::wire::Append<{element}>) {{ self.{field}.extend(delta.into_vec()); }}
                }}").unwrap();
        }
        if let Some(view) = &def.view {
            let path = def.rust.split('<').next().unwrap();
            let snapshot = super::calls::rust_ty(types, &view.snapshot, false);
            let field = &view.field;
            let put_snapshot = match types.snapshot_projection(view) {
                Some(fields) => fields
                    .iter()
                    .map(|f| format!("out.put(&self.{field}.{f});"))
                    .collect::<String>(),
                None => {
                    format!("let snapshot:{snapshot}=(&*self.{field}).into();out.put(&snapshot);")
                }
            };
            writeln!(out,"impl crate::wire::Put for {path}<'_> {{ fn put_to(&self,out:&mut crate::wire::Writer) {{ out.put(&*self.{field}); }} }} impl {path}<'_> {{ #[doc(hidden)] pub fn __wire_put_snapshot(&self,out:&mut crate::wire::Writer) {{ {put_snapshot} }} #[doc(hidden)] pub fn __wire_apply(&mut self,snapshot:{snapshot}) {{ self.{field}.apply_snapshot(snapshot); }} }}").unwrap();
        }
        if def.lifetimes != 0 || manual.contains(&def.rust.replace(' ', "")) {
            continue;
        }
        let body = match &def.kind {
            Kind::Record(list) => fields(types, list).map(|f| record(&def.rust, &f)),
            Kind::TupleRecord(items) => items
                .iter()
                .map(|t| spell(types, t))
                .collect::<Option<Vec<_>>>()
                .map(|t| tuple_record(&def.rust, &t)),
            Kind::Enum(names) => Some(enumeration(&def.rust, names)),
            Kind::Variant(cases) => variants(types, &def.rust, cases),
            Kind::Unit => Some(unit(&def.rust)),
            Kind::Json => Some(json(&def.rust)),
            Kind::Opaque => None,
        };
        match body {
            Some(code) => out.push_str(&code),
            // Written by hand beside the type: fail the build if it is missing.
            None => {
                let rust = &def.rust;
                writeln!(out, "const _: fn() = || {{ fn wire<T: crate::wire::Wire>() {{}} wire::<{rust}>(); }};").unwrap();
            }
        }
    }
    out
}

fn imp(rust: &str, min: &str, put: &str, take: &str) -> String {
    format!(
        "#[allow(unreachable_patterns, unused_variables)]\nimpl crate::wire::Wire for {rust} {{\nconst MIN: usize = {min};\nfn put(&self, out: &mut crate::wire::Writer) {{ {put} }}\nfn put_arena(&self, out: &mut crate::wire::ArenaWriter<'_>) {{ {put} }}\nfn take(input: &mut crate::wire::Reader<'_>) -> ::std::result::Result<Self, crate::wire::WireError> {{ {take} }}\n}}\n"
    )
}

fn with_owned(code: String, body: String) -> String {
    code.replacen(
        "fn take(input",
        &format!("fn put_owned(self,out: &mut crate::wire::Writer) {{ {body} }}\nfn take(input"),
        1,
    )
}
fn min_of(types: &[String]) -> String {
    let parts: Vec<String> = types
        .iter()
        .map(|t| format!("<{t} as crate::wire::Wire>::MIN"))
        .collect();
    if parts.is_empty() {
        "0".into()
    } else {
        parts.join(" + ")
    }
}

fn record(rust: &str, f: &[(&str, String)]) -> String {
    let put: String = f
        .iter()
        .map(|(n, _)| format!("out.put(&self.{n});"))
        .collect();
    let take: String = f
        .iter()
        .map(|(n, _)| format!("{n}: input.take()?,"))
        .collect();
    let min = min_of(&f.iter().map(|(_, t)| t.clone()).collect::<Vec<_>>());
    with_owned(
        imp(
            rust,
            &min,
            &put,
            &format!("input.nested(|input| Ok(Self {{ {take} }}))"),
        ),
        put.replace("out.put(&self.", "out.put_owned(self."),
    )
}

fn tuple_record(rust: &str, t: &[String]) -> String {
    let put: String = (0..t.len())
        .map(|i| format!("out.put(&self.{i});"))
        .collect();
    let take: String = t.iter().map(|_| "input.take()?,".to_string()).collect();
    with_owned(
        imp(
            rust,
            &min_of(t),
            &put,
            &format!("input.nested(|input| Ok(Self({take})))"),
        ),
        put.replace("out.put(&self.", "out.put_owned(self."),
    )
}

fn unit(rust: &str) -> String {
    imp(rust, "0", "", "Ok(Self)")
}

fn json(rust: &str) -> String {
    imp(
        rust,
        "4",
        "out.put_str(&::serde_json::to_string(self).unwrap_or_default());",
        "let text: ::std::string::String = input.take()?; ::serde_json::from_str(&text).map_err(|_| crate::wire::WireError::Invalid(\"not valid JSON for its type\"))",
    )
}

fn enumeration(rust: &str, names: &[String]) -> String {
    let put: String = names
        .iter()
        .enumerate()
        .map(|(i, n)| format!("Self::{n} => {i}u32,"))
        .collect();
    let take: String = names
        .iter()
        .enumerate()
        .map(|(i, n)| format!("{i} => Self::{n},"))
        .collect();
    imp(
        rust,
        "4",
        &format!(
            "out.put(&match self {{ {put} _ => unreachable!(\"every case was read from the enum's source\") }});"
        ),
        &format!(
            "Ok(match input.take::<u32>()? {{ {take} tag => return Err(crate::wire::WireError::Tag(tag)) }})"
        ),
    )
}

fn variants(types: &Types<'_>, rust: &str, cases: &[Case]) -> Option<String> {
    let mut put = String::new();
    let mut take = String::new();
    for (i, case) in cases.iter().enumerate() {
        let name = &case.rust;
        match &case.payload {
            Payload::None => {
                writeln!(put, "Self::{name} => out.put(&{i}u32),").unwrap();
                writeln!(take, "{i} => Self::{name},").unwrap();
            }
            Payload::Tuple(items) => {
                for item in items {
                    spell(types, item)?;
                }
                let binds: Vec<String> = (0..items.len()).map(|j| format!("f{j}")).collect();
                let puts: String = binds.iter().map(|b| format!("out.put({b});")).collect();
                writeln!(
                    put,
                    "Self::{name}({}) => {{ out.put(&{i}u32); {puts} }}",
                    binds.join(", ")
                )
                .unwrap();
                let takes: String = binds.iter().map(|_| "input.take()?,".to_string()).collect();
                writeln!(take, "{i} => Self::{name}({takes}),").unwrap();
            }
            Payload::Record(list) => {
                fields(types, list)?;
                let names: Vec<&str> = list.iter().map(|f| f.rust.as_str()).collect();
                let puts: String = names.iter().map(|n| format!("out.put({n});")).collect();
                writeln!(
                    put,
                    "Self::{name} {{ {} }} => {{ out.put(&{i}u32); {puts} }}",
                    names.join(", ")
                )
                .unwrap();
                let takes: String = names
                    .iter()
                    .map(|n| format!("{n}: input.take()?,"))
                    .collect();
                writeln!(take, "{i} => Self::{name} {{ {takes} }},").unwrap();
            }
        }
    }
    Some(with_owned(
        imp(
            rust,
            "4",
            &format!(
                "match self {{ {put} _ => unreachable!(\"every case was read from the enum's source\") }}"
            ),
            &format!(
                "input.nested(|input| Ok(match input.take::<u32>()? {{ {take} tag => return Err(crate::wire::WireError::Tag(tag)) }}))"
            ),
        ),
        format!(
            "match self {{ {} _ => unreachable!() }}",
            put.replace("out.put(&", "out.put_owned(")
                .replace("out.put(", "out.put_owned(")
        ),
    ))
}

/// A record field's type for its constructor, a nested borrowing record keeping the constructor's
/// lifetime (`Option<TerrainUvShift<'a>>`).
fn borrowed(types: &super::ty::Types<'_>, ty: &super::ty::Ty) -> String {
    use super::ty::Ty;
    match ty {
        Ty::Named(def) if types.defs[*def].lifetimes > 0 => {
            format!("{}<'_>", types.defs[*def].rust)
        }
        Ty::Option(item) => format!("Option<{}>", borrowed(types, item)),
        ty => super::calls::rust_ty(types, ty, false),
    }
}
